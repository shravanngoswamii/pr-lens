import { test, expect } from '@playwright/test';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { render } from '../../src/render.js';
import { designDocument } from '../design-fixture.js';
let dir, url;
test.beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'review-docs-design-'));
  await writeFile(join(dir, 'review.html'), await render(designDocument()));
  url = pathToFileURL(join(dir, 'review.html')).href;
});
test.afterAll(async () => rm(dir, { recursive: true, force: true }));

test('compares base and head offline and keeps removed definitions available for feedback', async ({ page, context }) => {
  await context.setOffline(true);
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => { window.copied = text; } } }));
  await page.goto(url);
  const graph = page.locator('#graph-calls');
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await expect(graph.getByRole('button', { name: 'type: New [added]', exact: true })).toBeVisible();
  await expect(graph.getByRole('button', { name: 'method: old [removed]', exact: true })).toBeVisible();
  await graph.getByRole('button', { name: 'Base', exact: true }).click();
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await expect(graph.getByRole('button', { name: 'type: New', exact: true })).toHaveCount(0);
  await expect(graph.getByRole('button', { name: 'method: old', exact: true })).toBeVisible();
  await graph.getByRole('button', { name: 'Head', exact: true }).click();
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await expect(graph.getByRole('button', { name: 'method: old', exact: true })).toHaveCount(0);
  await graph.getByRole('button', { name: 'Changes', exact: true }).click();
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await graph.getByRole('button', { name: 'Fit to view', exact: true }).click();
  await graph.getByRole('button', { name: 'Zoom in', exact: true }).click();
  await expect(graph.locator('output')).toHaveText('125%');
  await graph.locator('select').selectOption('3');
  await graph.getByRole('button', { name: 'Comment on this node', exact: true }).click();
  await page.getByLabel('Comment', { exact: true }).fill('Explain why the old handler was removed.');
  await page.getByRole('button', { name: 'Add comment', exact: true }).click();
  await page.getByRole('button', { name: 'Copy agent prompt', exact: true }).click();
  expect(await page.evaluate(() => window.copied)).toContain('old(x::Int)');
  expect(await page.evaluate(() => window.copied)).toContain(designDocument().review.base);
});

test('filters inventory gaps and opens the linked definition in the appropriate graph view', async ({ page }) => {
  await page.goto(url);
  const graph = page.locator('#graph-calls');
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await graph.getByRole('button', { name: 'Base', exact: true }).click();
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await page.locator('.sidebar nav a[data-view="section-definitions"]').click();
  const inventory = page.locator('.definition-inventory');
  await inventory.getByLabel('Coverage', { exact: true }).selectOption('unassigned');
  await expect(inventory.locator('.definition-item:visible')).toHaveCount(1);
  await expect(inventory.locator('.definition-item:visible')).toContainText('pending');
  await inventory.getByLabel('Coverage', { exact: true }).selectOption('');
  await inventory.getByLabel('Search definitions', { exact: true }).fill('New');
  await expect(inventory.locator('.definition-item:visible')).toHaveCount(1);
  await inventory.locator('.definition-item:visible > summary').click();
  await inventory.getByRole('link', { name: 'Design change / New', exact: true }).click();
  await expect(graph).toHaveAttribute('data-revision-view', 'changes');
  await expect(graph.locator('.selection h4')).toHaveText('New');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Views', exact: true }).click();
  await page.locator('.sidebar nav a[data-view="section-definitions"]').click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('saves the selected revision and editable inventory without treating source names as HTML', async ({ page, browser }) => {
  const doc = designDocument();
  doc.sections[1].blocks[0].data.items[3].name = '</script><img src=x onerror="window.pwned=1">';
  const input = join(dir, 'hostile.html');
  await writeFile(input, await render(doc));
  await page.goto(pathToFileURL(input).href);
  const graph = page.locator('#graph-calls');
  await expect(graph).toHaveAttribute('data-ready', 'true');
  expect(await page.locator('img').count()).toBe(0);
  expect(await page.evaluate(() => window.pwned)).toBeUndefined();
  await graph.getByRole('button', { name: 'Base', exact: true }).click();
  await expect(graph).toHaveAttribute('data-ready', 'true');
  await page.locator('.save-menu > summary').click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'HTML with comments', exact: true }).click();
  const parts = [];
  for await (const part of await (await pending).createReadStream()) parts.push(part);
  const saved = join(dir, 'saved.html'); await writeFile(saved, Buffer.concat(parts));
  const context = await browser.newContext({ offline: true }); const reader = await context.newPage();
  await reader.goto(pathToFileURL(saved).href);
  await expect(reader.locator('#graph-calls')).toHaveAttribute('data-ready', 'true');
  await expect(reader.getByRole('button', { name: 'Base', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(reader.getByRole('button', { name: 'method: old', exact: true })).toBeVisible();
  expect(await reader.locator('img').count()).toBe(0);
  const embedded = await reader.locator('#review-data').textContent();
  expect(JSON.parse(embedded)).toEqual(doc);
  await context.close();
});
